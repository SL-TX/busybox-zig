#!/usr/bin/env python3
"""Capture the reference busybox meta-CLI banner and no-args body.

The reference binary's ``--version`` line and its no-argument output are
build-specific (the parenthesized timestamp changes every build). This script
records one exact reference build as a golden text artifact and emits a Zig
module with the same bytes. The banner and body are kept as separate constants
so differential tests can normalize the timestamp without touching the body.

Regenerate with::

    python3 scripts/parity/gen_meta_golden.py \
        --ref /tmp/opencode/bb-ref2/busybox
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEFAULT_REF = "/tmp/opencode/bb-ref2/busybox"
DEFAULT_GOLDEN = os.path.join(REPO_ROOT, "tests", "parity", "golden", "meta.txt")
DEFAULT_ZIG = os.path.join(REPO_ROOT, "src", "generated", "meta.zig")

VERSION_MARK = "===VERSION===\n"
BODY_MARK = "===NOARGS_BODY===\n"


def run(ref: str, *args: str) -> bytes:
    return subprocess.run([ref, *args], stdout=subprocess.PIPE, check=True).stdout


def zig_string(data: bytes) -> str:
    out = ['"']
    for ch in data:
        if ch == 0x5C:  # backslash
            out.append("\\\\")
        elif ch == 0x22:  # double quote
            out.append('\\"')
        elif ch == 0x0A:
            out.append("\\n")
        elif ch == 0x0D:
            out.append("\\r")
        elif ch == 0x09:
            out.append("\\t")
        elif 0x20 <= ch < 0x7F:
            out.append(chr(ch))
        else:
            out.append("\\x%02x" % ch)
    out.append('"')
    return "".join(out)


def golden_text(version: bytes, body: bytes) -> str:
    return VERSION_MARK + version.decode("ascii") + BODY_MARK + body.decode("ascii")


def zig_text(version: bytes, body: bytes) -> str:
    return "\n".join([
        "// Generated by scripts/parity/gen_meta_golden.py - DO NOT EDIT.",
        "// Source: reference BusyBox 1.39.0.git binary (tests/parity/golden/meta.txt).",
        "// Regenerate with:",
        "//   python3 scripts/parity/gen_meta_golden.py --ref <reference-busybox>",
        "",
        "pub const version = " + zig_string(version) + ";",
        "pub const noargs_body = " + zig_string(body) + ";",
        'pub const first_line = version[0 .. version.len - 1] ++ " multi-call binary.\\n";',
        'pub const noargs = first_line ++ noargs_body;',
        "",
        'test "meta golden is self-consistent" {',
        '    const std = @import("std");',
        "    try std.testing.expect(std.mem.eql(u8, first_line, version[0 .. version.len - 1] ++ \" multi-call binary.\\n\"));",
        "    try std.testing.expect(std.mem.startsWith(u8, noargs, first_line));",
        "    try std.testing.expect(std.mem.endsWith(u8, version, \"\\n\"));",
        "    try std.testing.expect(std.mem.endsWith(u8, noargs, \"\\n\"));",
        "}",
        "",
    ])


def write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)
    print("wrote " + path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ref", default=DEFAULT_REF, help="reference busybox binary")
    parser.add_argument("--golden", default=DEFAULT_GOLDEN, help="golden text output")
    parser.add_argument("--zig", default=DEFAULT_ZIG, help="generated Zig module output")
    parser.add_argument("--check", action="store_true", help="fail if the committed files are stale")
    args = parser.parse_args(argv)

    version = run(args.ref, "--version")
    noargs = run(args.ref)
    # The no-args first line is the version banner (without its trailing
    # newline) followed by " multi-call binary." and a newline.
    prefix = version.rstrip(b"\n") + b" multi-call binary.\n"
    if not noargs.startswith(prefix):
        print("reference no-args output does not start with the version banner", file=sys.stderr)
        return 1

    golden = golden_text(version, noargs[len(prefix):])
    zig = zig_text(version, noargs[len(prefix):])
    if args.check:
        ok = True
        for path, text in ((args.golden, golden), (args.zig, zig)):
            if not os.path.exists(path):
                print("missing " + path, file=sys.stderr)
                ok = False
            elif open(path, encoding="utf-8", newline="").read() != text:
                print(path + " is stale; regenerate with gen_meta_golden.py", file=sys.stderr)
                ok = False
        if ok:
            print("meta golden in sync")
        return 0 if ok else 1

    write(args.golden, golden)
    write(args.zig, zig)
    print("captured version line (%d bytes) and no-args body (%d bytes)" % (len(version), len(noargs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
