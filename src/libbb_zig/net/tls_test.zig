test "TLS SHA primitives" {
    var d20: [20]u8 = undefined;
    tls.sha.sha1("abc", &d20);
    const h20 = try tls.sha.toHex(a, &d20);
    defer a.free(h20);
    try std.testing.expectEqualStrings("a9993e364706816aba3e25717850c26c9cd0d89d", h20);

    var d32: [32]u8 = undefined;
    tls.sha.sha256("abc", &d32);
    const h32 = try tls.sha.toHex(a, &d32);
    defer a.free(h32);
    try std.testing.expectEqualStrings("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", h32);

    var mac: [32]u8 = undefined;
    tls.sha.hmacSha256("key", "The quick brown fox jumps over the lazy dog", &mac);
    const hm = try tls.sha.toHex(a, &mac);
    defer a.free(hm);
    try std.testing.expectEqualStrings("f7bc83f430538424b13298e6aa6fb143ef4d59a14946175997479dbc2d1a3cd8", hm);

    const raw = try tls.sha.fromHex(a, "0a0bff");
    defer a.free(raw);
    try std.testing.expectEqualSlices(u8, &[_]u8{ 0x0a, 0x0b, 0xff }, raw);
}

