test "TLS record layer and handshake framing" {
    const frame = try tls.record.makeHandshake(a, 1, "hello");
    defer a.free(frame);
    const hs = try tls.record.parseHandshake(frame);
    try std.testing.expectEqual(@as(u8, 1), hs.msg_type);
    try std.testing.expectEqualStrings("hello", hs.body);

    const rec = try tls.record.serialize(a, .handshake, 0x0303, frame);
    defer a.free(rec);
    const parsed = try tls.record.parse(rec);
    try std.testing.expectEqual(tls.record.ContentType.handshake, parsed.content_type);
    try std.testing.expectEqual(@as(u16, 0x0303), parsed.version);
    try std.testing.expectEqualSlices(u8, frame, parsed.fragment);
}

const Sh = struct {
    fn run(fd: net.fd_t) void {
        const s = fd;
        const conn = net.accept(s) catch return;
        defer net.close(conn);
        var buf: [4096]u8 = undefined;
        const n = net.recv(conn, &buf, 0) catch return;
        const rec = tls.record.parse(buf[0..n]) catch return;
        if (rec.content_type != .handshake) return;
        const hs = tls.record.parseHandshake(rec.fragment) catch return;
        if (hs.msg_type != 1) return;
        var full: [38]u8 = undefined;
        @memset(&full, 0);
        full[0] = 0x03;
        full[1] = 0x03;
        for (2..34) |i| full[i] = @intCast(i);
        full[35] = 0x00;
        full[36] = 0x2f;
        full[37] = 0x00;
        const hsmsg = tls.record.makeHandshake(std.heap.page_allocator, 2, &full) catch return;
        defer std.heap.page_allocator.free(hsmsg);
        const reply = tls.record.serialize(std.heap.page_allocator, .handshake, 0x0303, hsmsg) catch return;
        defer std.heap.page_allocator.free(reply);
        net.sendAll(conn, reply, 0) catch {};
    }
};

test "TLS ClientHello/ServerHello framing against local test server" {
    const listener = try net.createAndListen(net.Address.initV4(.{ 127, 0, 0, 1 }, 0), 1);
    defer net.close(listener);
    const addr = try net.localAddr(listener);
    const t = try std.Thread.spawn(.{}, Sh.run, .{listener});
    defer t.join();

    const fd = try net.createAndConnect(addr);
    defer net.close(fd);
    var client = try tls.Client.init(a, fd, "test.local", .{});
    defer client.deinit();
    try client.sendClientHello();

    const sh = try client.readServerHello();
    try std.testing.expectEqual(@as(u16, 0x0303), sh.version);
    try std.testing.expectEqual(@as(u16, 0x002f), sh.cipher_suite);
    try std.testing.expectEqual(@as(u8, 0), sh.compression);
    try std.testing.expectEqual(@as(u8, 2), sh.random[0]);
}
