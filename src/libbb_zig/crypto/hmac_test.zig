const std = @import("std");
const hmac = @import("libbb_zig").crypto.hmac;

test "hmac-sha1 RFC 2202 case 1" {
    const key = "\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b\x0b";
    var out: [20]u8 = undefined;
    hmac.sha1(key, "Hi There", &out);
    try std.testing.expectEqualStrings("\xb6\x17\x31\x86\x55\x05\x72\x64\xe2\x8b\xc0\xb6\xfb\x37\x8c\x8e\xf1\x46\xbe\x00", &out);
}

test "hmac-sha256 RFC 4231 case 2" {
    var out: [32]u8 = undefined;
    hmac.sha256("key", "The quick brown fox jumps over the lazy dog", &out);
    try std.testing.expectEqualStrings("\xf7\xbc\x83\xf4\x30\x53\x84\x24\xb1\x32\x98\xe6\xaa\x6f\xb1\x43\xef\x4d\x59\xa1\x49\x46\x17\x59\x97\x47\x9d\xbc\x2d\x1a\x3c\xd8", &out);
}

test "hmac-sha512 RFC 4231 case 2" {
    var out: [64]u8 = undefined;
    hmac.sha512("key", "The quick brown fox jumps over the lazy dog", &out);
    try std.testing.expectEqualStrings(
        "\xb4\x2a\xf0\x90\x57\xba\xc1\xe2\xd4\x17\x08\xe4\x8a\x90\x2e\x09" ++
            "\xb5\xff\x7f\x12\xab\x42\x8a\x4f\xe8\x66\x53\xc7\x3d\xd2\x48\xfb" ++
            "\x82\xf9\x48\xa5\x49\xf7\xb7\x91\xa5\xb4\x19\x15\xee\x4d\x1e\xc3" ++
            "\x93\x53\x57\xe4\xe2\x31\x72\x50\xd0\x37\x2a\xfa\x2e\xbe\xeb\x3a",
        &out,
    );
}
