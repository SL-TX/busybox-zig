const std = @import("std");
const sha3 = @import("libbb_zig").crypto.sha3;

test "sha3-256 abc matches NIST FIPS 202" {
    var out: [32]u8 = undefined;
    sha3.hash256("abc", &out);
    try std.testing.expectEqualStrings("\x3a\x98\x5d\xa7\x4f\xe2\x25\xb2\x04\x5c\x17\x2d\x6b\xd3\x90\xbd\x85\x5f\x08\x6e\x3e\x9d\x52\x5b\x46\xbf\xe2\x45\x11\x43\x15\x32", &out);
}

test "sha3-512 abc matches NIST FIPS 202" {
    var out: [64]u8 = undefined;
    sha3.hash512("abc", &out);
    try std.testing.expectEqualStrings(
        "\xb7\x51\x85\x0b\x1a\x57\x16\x8a\x56\x93\xcd\x92\x4b\x6b\x09\x6e" ++
            "\x08\xf6\x21\x82\x74\x44\xf7\x0d\x88\x4f\x5d\x02\x40\xd2\x71" ++
            "\x2e\x10\xe1\x16\xe9\x19\x2a\xf3\xc9\x1a\x7e\xc5\x76\x47\xe3\x93" ++
            "\x40\x57\x34\x0b\x4c\xf4\x08\xd5\xa5\x65\x92\xf8\x27\x4e\xec\x53\xf0",
        &out,
    );
}

test "keccak256 abc" {
    var out: [32]u8 = undefined;
    sha3.keccak256("abc", &out);
    try std.testing.expectEqualStrings("\x4e\x03\x65\x7a\xea\x45\xa9\x4f\xc7\xd4\x7b\xa8\x26\xc8\xd6\x67\xc0\xd1\xe6\xe3\x3a\x64\xa0\x36\xec\x44\xf5\x8f\xa1\x2d\x6c\x45", &out);
}
