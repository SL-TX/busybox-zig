test "PEM private key parses and PKCS#1 v1.5 decrypt round-trips" {
    var key = try rsa.parsePrivateKeyPem(a, PEM);
    defer key.deinit(a);
    try std.testing.expectEqual(@as(usize, 256), key.modulus.len);

    const info = try cert.extract(&CERT);
    var pubkey = try rsa.parsePublicKeyDer(a, info.spki);
    defer pubkey.deinit(a);

    var premaster: [48]u8 = undefined;
    premaster[0] = 3;
    premaster[1] = 3;
    for (2..48) |i| premaster[i] = @intCast(i);

    const em = try a.alloc(u8, pubkey.modulus.len);
    defer a.free(em);
    em[0] = 0;
    em[1] = 2;
    @memset(em[2 .. em.len - 49], 0xab);
    em[em.len - 49] = 0;
    @memcpy(em[em.len - 48 ..], &premaster);
    const ciphertext = try rsa.powModFast(a, em, pubkey.exponent, pubkey.modulus);
    defer a.free(ciphertext);
    const plain = try rsa.decryptPkcs1V15(a, key, ciphertext);
    defer a.free(plain);
    try std.testing.expectEqualSlices(u8, &premaster, plain);
}

test "certificate chain self-signature and hostname validation" {
    try cert.verifyChain(a, &.{&CERT}, "localhost");
    try std.testing.expectError(error.CertificateHostMismatch, cert.verifyHostName(&CERT, "wrong.example"));
}

test "TLS 1.2 PRF and record framing basics" {
    const out = try prf.tlsPrfSha256(a, "secret", "label", "seed", 100);
    defer a.free(out);
    try std.testing.expectEqual(@as(usize, 100), out.len);
    const rec_bytes = try rec.serialize(a, .handshake, 0x0303, "abc");
    defer a.free(rec_bytes);
    const parsed = try rec.parse(rec_bytes);
    try std.testing.expectEqualStrings("abc", parsed.fragment);
    const hs = try rec.makeHandshake(a, 1, "body");
    defer a.free(hs);
    const h = try rec.parseHandshake(hs);
    try std.testing.expectEqual(@as(u8, 1), h.msg_type);
    try std.testing.expectEqualStrings("body", h.body);
    var digest: [32]u8 = undefined;
    sha.sha256("body", &digest);
    try std.testing.expectEqual(@as(usize, 32), digest.len);
}
